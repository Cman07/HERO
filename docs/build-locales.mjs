// Rebuild the offline bundle after editing public translations. No network.
import { readFile, writeFile } from 'node:fs/promises';
const source = JSON.parse(await readFile(new URL('./localization-source.json', import.meta.url), 'utf8'));
const packs = {};
try { packs.es = JSON.parse(await readFile(new URL('../locales/es.json', import.meta.url), 'utf8')); } catch { packs.es = {}; }
for (const language of ['ar', 'zh-Hans', 'ko', 'vi', 'tl', 'fr']) {
  const pack = JSON.parse(await readFile(new URL(`../locales/${language}.json`, import.meta.url), 'utf8'));
  for (const key of source) {
    if (typeof pack[key] !== 'string' || !pack[key].trim()) throw new Error(`Missing ${language}: ${key}`);
    for (const token of key.match(/\{\w+\}|\b911\b/g) || []) {
      if (!pack[key].includes(token)) throw new Error(`Missing literal ${language}: ${token}`);
    }
  }
  packs[language] = pack;
}
await writeFile(new URL('../locales.cjs', import.meta.url), `// Generated by docs/build-locales.mjs from public locales/*.json.\n(() => {\nconst packs = ${JSON.stringify(packs, null, 2)};\nif (typeof module !== 'undefined') module.exports = packs;\nif (typeof window !== 'undefined') window.heroLocalePacks = packs;\n})();\n`);
console.log(`Bundled ${source.length} strings in each of ${Object.keys(packs).length} additional languages.`);
